"""Generate the D049 257-entry positive quarter-wave Q15 sine table."""

from __future__ import annotations

import hashlib
import math
import struct
import sys
from pathlib import Path

EXPECTED_SHA256 = "6062d337f69ac6ae99b7da9cdf95f87aea1ee04a9110f26839f0a85f74efff68"
ENTRIES = 257


def values() -> list[int]:
    return [
        int(math.floor(math.sin((math.pi / 2.0) * i / 256.0) * 32767.0 + 0.5))
        for i in range(ENTRIES)
    ]


def render_table(data: list[int]) -> str:
    rows = []
    for start in range(0, ENTRIES, 8):
        chunk = data[start:start + 8]
        suffix = "," if start + 8 < ENTRIES else ""
        rows.append("    " + ", ".join(str(value) for value in chunk) + suffix)
    return (
        "/* SPDX-License-Identifier: GPL-3.0-only */\n"
        "/* Generated by tools/gen_wp5_1_fm_sine.py. Do not hand-edit. */\n"
        "static const int16_t fmt_fm_sine_quarter_q15[FMT_FM_SINE_QUARTER_ENTRIES] = {\n"
        + "\n".join(rows)
        + "\n};\n"
    )


def main() -> int:
    if len(sys.argv) != 2:
        print(f"usage: {Path(sys.argv[0]).name} OUTPUT", file=sys.stderr)
        return 2

    data = values()
    payload = b"".join(struct.pack("<h", value) for value in data)
    digest = hashlib.sha256(payload).hexdigest()
    if digest != EXPECTED_SHA256:
        raise SystemExit(f"D049 table hash mismatch: {digest}")

    out = Path(sys.argv[1])
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render_table(data), encoding="utf-8", newline="\n")
    print(
        "WP5_1_FM_SINE_GENERATOR_OK=1 "
        f"entries={len(data)} payload_bytes={len(payload)} sha256={digest}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
