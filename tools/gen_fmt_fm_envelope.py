import hashlib
import struct
import sys
from pathlib import Path

LEVEL_MAX_Q15_16 = 32767 << 16
EXPECTED_SHA256 = "6e94aa6553b78919913d49a24c80ca7317c913fff344294a107137f85ffbc025"


def target_samples(control):
    if control == 0:
        return 0
    x = control - 1
    octave = x >> 4
    frac = x & 15
    return ((44 * (16 + frac) * (1 << octave)) + 8) >> 4


def build_table():
    table = [0]
    for control in range(1, 256):
        samples = target_samples(control)
        step = (LEVEL_MAX_Q15_16 + samples - 1) // samples
        table.append(step)
    assert len(table) == 256
    assert len(set(table[1:])) == 255
    assert all(table[i] > table[i + 1] for i in range(1, 255))
    return table


def serialize(table):
    return b"".join(struct.pack("<I", value) for value in table)


def render(table):
    lines = [
        "/* SPDX-License-Identifier: GPL-3.0-only */",
        "/* Generated by tools/gen_fmt_fm_envelope.py. Do not edit by hand. */",
        "static const uint32_t fmt_fm_envelope_step_q15_16[256] = {",
    ]
    for index in range(0, 256, 8):
        values = ", ".join(f"{value}u" for value in table[index:index + 8])
        lines.append(f"    {values},")
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def main():
    path = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("firmware/gen/fmt_fm_envelope_step_q15_16.inc")
    table = build_table()
    payload = serialize(table)
    digest = hashlib.sha256(payload).hexdigest()
    assert len(payload) == 1024
    assert digest == EXPECTED_SHA256, digest
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(table))
    print(f"FMT_FM_ENVELOPE_TABLE_OK=1 entries=256 bytes=1024 sha256={digest}")


if __name__ == "__main__":
    main()
