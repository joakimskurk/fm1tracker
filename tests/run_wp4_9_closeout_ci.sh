#!/bin/sh
# SPDX-License-Identifier: GPL-3.0-only
set -eu
cd "$(dirname "$0")/.."
mkdir -p build build/host build/tests

GATE4_PRODUCTION=c93c39ad344760b4da0dfbc76829ca5fef886174
EXPECTED_HOST_WAV=17fa5ce1759cb728e152d1d3d417a51a13d358908bdcc2dc2e505c27c86a1076
EXPECTED_BIN=214fba8ec0af4be3120bc91dafbaa24e7d4d8a5a6de7395de2473f12374c4215
EXPECTED_FWSC=20f0bbe556edcf6a00118f9983335913dda2f29fc64d3c87997bfd6756bcf119
EXPECTED_SDK=d179b4484759423312073f5fbb232501aa491047

# Gate 5/6 are verification-only work. No production source, HAL, loader,
# linker/build infrastructure or tooling may have changed since the final Gate 4
# source-hygiene checkpoint.
git diff --exit-code "$GATE4_PRODUCTION" -- \
    firmware/src firmware/hal firmware/loader firmware/app.ld build.sh tools
printf '%s\n' 'WP4_9_CLOSEOUT_PRODUCTION_FREEZE_OK=1 gate4_checkpoint=c93c39ad344760b4da0dfbc76829ca5fef886174'

# Canonical linked-audio matrix: all four engines, mixed/eight-track ownership,
# D033 sample timing and D031/D032/D044 precedence.
sh tests/run_wp4_9_linked_audio_host.sh | tee build/wp4_9_closeout_gate5.log
grep -F 'WP4_9_GATE5_CANONICAL_OK=1' build/wp4_9_closeout_gate5.log
grep -F 'WP4_9_GATE5_HOST_MATRIX_CANONICAL_OK=1' build/wp4_9_closeout_gate5.log
grep -F 'delay3_first_nonzero_frame=2757' build/wp4_9_closeout_gate5.log
grep -F 'retrig2_first_diff_frame=1838' build/wp4_9_closeout_gate5.log
grep -F 'cut3_first_diff_frame=2757' build/wp4_9_closeout_gate5.log

# Canonical inherited non-obsolete regression suite + D045 realtime audit.
sh tests/run_wp4_9_inherited_regressions.sh | tee build/wp4_9_closeout_gate6.log
grep -F 'WP4_9_GATE6_REALTIME_AUDIT_OK=1' build/wp4_9_closeout_gate6.log
grep -F 'WP4_9_GATE6_INHERITED_REGRESSIONS_OK=1 obsolete_proof_sine_hashes_excluded=1' build/wp4_9_closeout_gate6.log
grep -F 'WP4_9_UI_CANONICAL_HASHES_OK=1' build/wp4_9_gate6_ui_context.log

# Default full app is now intentionally linked 8-BIT audio, not the historical
# proof sine. Freeze the complete host WAV generated by the normal app harness.
sh tests/run_host.sh | tee build/wp4_9_closeout_default_host.log
HOST_SHA="$(sha256sum build/host/fm1tracker.wav | awk '{print $1}')"
HOST_FRAMES="$(python3 - <<'PY'
import wave
with wave.open('build/host/fm1tracker.wav', 'rb') as f:
    print(f.getnframes())
PY
)"
test "$HOST_SHA" = "$EXPECTED_HOST_WAV"
test "$HOST_FRAMES" = '286464'
printf 'WP4_9_DEFAULT_LINKED_AUDIO_OK=1 sha256=%s frames=%s\n' "$HOST_SHA" "$HOST_FRAMES" | tee build/wp4_9_closeout_default_audio.txt

# Pinned real target build. Do not substitute a host compiler or an unpinned SDK.
: "${RUNNER_TEMP:?RUNNER_TEMP is required for the pinned target closeout}"
./tools/get_toolchain.sh "$RUNNER_TEMP/jieli"
test -x "$RUNNER_TEMP/jieli/toolchain/pi32v2/bin/clang"
export JIELI_TOOLCHAIN="$RUNNER_TEMP/jieli/toolchain"
"$JIELI_TOOLCHAIN/pi32v2/bin/clang" --version | head -n 2 | tee build/wp4_9_closeout_toolchain.txt

SDK="$RUNNER_TEMP/ac79-sdk"
rm -rf "$SDK"
git clone --depth 1 --branch AC79NN_SDK_V1.2.1_2023-12-13 \
    https://gitee.com/Jieli-Tech/fw-AC79_AIoT_SDK.git "$SDK"
ACTUAL_SDK="$(git -C "$SDK" rev-parse HEAD)"
test "$ACTUAL_SDK" = "$EXPECTED_SDK"
printf 'AC79_SDK_COMMIT=%s\n' "$ACTUAL_SDK" | tee build/wp4_9_closeout_sdk.txt
export AC79_SDK="$SDK"

./build.sh --release 0.1 | tee build/wp4_9_closeout_device.log
test -s build/fm1tracker.bin
test -s build/fm1tracker-0.1.fwsc
test -s build/fm1tracker.elf
"$JIELI_TOOLCHAIN/common/bin/objdump" -t build/fm1tracker.elf > build/wp4_9_closeout_symbols.txt

python3 - <<'PY' | tee build/wp4_9_closeout_metrics.txt
import hashlib, re
from pathlib import Path

EXPECTED_BIN = '214fba8ec0af4be3120bc91dafbaa24e7d4d8a5a6de7395de2473f12374c4215'
EXPECTED_FWSC = '20f0bbe556edcf6a00118f9983335913dda2f29fc64d3c87997bfd6756bcf119'
log = Path('build/wp4_9_closeout_device.log').read_text()
m = re.search(r'image (\d+) B of (\d+); RAM \.data\+\.bss (\d+) B of 98304; pool (\d+) B of 344064', log)
assert m, log[-4000:]
image, image_limit, ram, pool = map(int, m.groups())

# Gate 4 target-smoke values are now the exact WP4.9 linked baseline.
assert image == 72504, image
assert ram == 19604, ram
assert pool == 113000, pool

# D037 Phase-4 ceilings remain the normative budget boundary.
assert image <= 132496, image
assert ram <= 21488, ram
assert pool <= 129384, pool

def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()

bin_sha = sha('build/fm1tracker.bin')
fwsc_sha = sha('build/fm1tracker-0.1.fwsc')
assert bin_sha == EXPECTED_BIN, bin_sha
assert fwsc_sha == EXPECTED_FWSC, fwsc_sha

print('WP4_9_CLOSEOUT_TARGET_METRICS')
print(f'image_bytes={image}')
print(f'normal_ram_bytes={ram}')
print(f'pool_ram_bytes={pool}')
print(f'image_delta_vs_wp4_8={image-66960}')
print(f'normal_ram_delta_vs_wp4_8={ram-13296}')
print(f'pool_delta_vs_wp4_8={pool-113000}')
print(f'image_remaining_to_d037={132496-image}')
print(f'normal_ram_remaining_to_d037={21488-ram}')
print(f'pool_remaining_to_d037={129384-pool}')
print(f'fm1tracker_bin_sha256={bin_sha}')
print(f'fm1tracker_fwsc_sha256={fwsc_sha}')
PY

grep -F 'FM1Tracker package' build/wp4_9_closeout_device.log
grep -F 'identity FM-1_987' build/wp4_9_closeout_device.log
grep -F 'image_bytes=72504' build/wp4_9_closeout_metrics.txt
grep -F 'normal_ram_bytes=19604' build/wp4_9_closeout_metrics.txt
grep -F 'pool_ram_bytes=113000' build/wp4_9_closeout_metrics.txt
grep -F 'image_remaining_to_d037=59992' build/wp4_9_closeout_metrics.txt
grep -F 'normal_ram_remaining_to_d037=1884' build/wp4_9_closeout_metrics.txt
grep -F 'pool_remaining_to_d037=16384' build/wp4_9_closeout_metrics.txt
grep -F "fm1tracker_bin_sha256=$EXPECTED_BIN" build/wp4_9_closeout_metrics.txt
grep -F "fm1tracker_fwsc_sha256=$EXPECTED_FWSC" build/wp4_9_closeout_metrics.txt

printf '%s\n' 'WP4_9_CLOSEOUT_OK=1 gates=5,6 host=linked_8bit target=pinned d037_ceiling=pass hardware_margin_claim=none' | tee build/wp4_9_closeout_summary.txt
